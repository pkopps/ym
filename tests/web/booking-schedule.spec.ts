import { test, expect } from "./fixtures";
import { apiBaseUrl, registerProvider, registerCustomer, approveProvider, createBooking, authenticatedPost, loginUi, captureResponsiveEvidence, testPassword } from "./workflow-helpers";
import type { Booking } from "@yardmatch/contracts";

test("weather hold and customer-approved reschedule are visible across responsive booking screens", async ({ page, request }) => {
  test.setTimeout(120000);
  const provider = await registerProvider(request);
  await approveProvider(request, provider.providerId, provider.token);
  const customer = await registerCustomer(request, "Weather Customer");
  const booking = await createBooking(request, { customerToken: customer.token, providerId: provider.providerId, hoursFromNow: 8 });
  await authenticatedPost(request, provider.token, "/api/bookings/confirm", { bookingId: booking.id });
  const unauthorized = await request.post(`${apiBaseUrl}/api/bookings/schedule-update`, { headers: { Authorization: `Bearer ${customer.token}` }, data: { bookingId: booking.id, kind: "weather" } });
  expect(unauthorized.status()).toBe(403);
  await loginUi(page, "provider", provider.email);
  await page.goto("/provider/management");
  const panel = page.getByRole("region", { name: "Visit timing updates" }).first();
  await panel.getByText("Update customer about timing", { exact: true }).click();
  await panel.getByLabel("What changed?").selectOption("weather");
  await panel.getByLabel("What should the customer know?").fill("Heavy rain has left the ground saturated. We are checking safe working conditions.");
  await panel.getByRole("button", { name: "Notify customer", exact: true }).click();
  await expect(panel.getByRole("heading", { name: "Weather hold" })).toBeVisible();
  await expect(panel.getByText(/Next update by/)).toBeVisible();
  await captureResponsiveEvidence(page, "schedule-provider-weather", panel);

  await panel.getByLabel("What changed?").selectOption("reschedule");
  const date = new Date(Date.now() + 48 * 3600000).toISOString().slice(0, 10);
  await panel.getByLabel("New service date").fill(date);
  await panel.getByLabel("Arrival window").selectOption("12");
  await panel.getByRole("button", { name: "Notify customer", exact: true }).click();
  await expect(panel.getByRole("heading", { name: "New window proposed" })).toBeVisible();
  await page.goto("/login/customer");
  await page.getByLabel("Email").fill(customer.email);
  await page.getByLabel("Password", { exact: true }).fill(testPassword);
  await page.getByRole("button", { name: "Log in", exact: true }).click();
  await page.goto(`/customer/dashboard?bookingId=${booking.id}`);
  const customerPanel = page.getByRole("region", { name: "Visit timing updates" }).first();
  await expect(customerPanel.getByRole("button", { name: "Accept new window" })).toBeVisible();
  await expect(customerPanel.getByText(/Afternoon/)).toBeVisible();
  await captureResponsiveEvidence(page, "schedule-customer-proposal", customerPanel);
  await customerPanel.getByRole("button", { name: "This does not work" }).click();
  await expect(customerPanel.getByRole("heading", { name: "Another window needed" })).toBeVisible();
  const current = await request.get(`${apiBaseUrl}/api/bookings?customerId=${customer.customerId}`, { headers: { Authorization: `Bearer ${customer.token}` } });
  expect(current.ok()).toBeTruthy();
  const response = await current.json();
  const bookings: Booking[] = Array.isArray(response) ? response : response.items ?? response.bookings;
  const declined = bookings.find(item => item.id === booking.id)!;
  expect(declined.scheduleUpdates!.at(-1)!.state).toBe("declined");
  const proposal = declined.scheduleUpdates!.at(-1)!;
  await authenticatedPost(request, provider.token, "/api/bookings/schedule-update", { bookingId: booking.id, kind: "reschedule", reason: "A dry afternoon is available for your visit.", nextUpdateByIso: new Date(Date.now() + 3600000).toISOString(), proposedStartIso: proposal.proposedStartIso, proposedEndIso: proposal.proposedEndIso });
  await page.reload();
  await customerPanel.getByRole("button", { name: "Accept new window" }).click();
  await expect(customerPanel.getByRole("heading", { name: "New visit confirmed" })).toBeVisible();
  await expect(customerPanel.getByText("Only this visit moved. The price and recurring plan stay the same.")).toBeVisible();
  await captureResponsiveEvidence(page, "schedule-customer-confirmed", customerPanel);
});
